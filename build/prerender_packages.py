# -*- coding: utf-8 -*-
"""Write the package markup into index.html.

It does not re-implement the template: it runs the site's own
buildPackagesHtml() in headless Chrome and writes back exactly what the browser
produced, so the static HTML cannot drift from the JavaScript.

Usage:  python build/prerender_packages.py
"""
import html as htmllib
import io, os, re, subprocess, sys, tempfile, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HOST = os.path.join(ROOT, "build", "_prerender_host.html")
TARGET = os.path.join(ROOT, "index.html")

CHROME_CANDIDATES = [
    r"C:\Program Files\Google\Chrome\Application\chrome.exe",
    r"C:\Program Files (x86)\Google\Chrome\Application\chrome.exe",
]

BEGIN = "<!-- BUILD:packages -->"
END = "<!-- /BUILD:packages -->"


def chrome():
    for c in CHROME_CANDIDATES:
        if os.path.exists(c):
            return c
    sys.exit("Chrome not found")


def render():
    url = urllib.request.pathname2url(HOST)
    profile = tempfile.mkdtemp(prefix="cornel-prerender-")
    cmd = [chrome(), "--headless=new", "--disable-gpu", "--no-first-run",
           "--user-data-dir=" + profile, "--virtual-time-budget=8000",
           "--dump-dom", "file:" + url]
    dom = subprocess.check_output(cmd, stderr=subprocess.DEVNULL).decode("utf-8", "replace")
    m = re.search(r'<pre id="out">(.*?)</pre>', dom, re.S)
    if not m:
        sys.exit("could not read build output from Chrome")
    out = htmllib.unescape(m.group(1))
    if out.startswith("BUILD_ERROR") or not out.strip():
        sys.exit("build failed: " + out[:300])
    return out.strip()


def indent(markup, pad="            "):
    lines = [l.rstrip() for l in markup.splitlines()]
    while lines and not lines[0].strip():
        lines.pop(0)
    return "\n".join((pad + l) if l.strip() else "" for l in lines)


def normalise(s):
    """Element-for-element comparison: indentation and line breaks between
    tags are irrelevant, everything else must match."""
    s = re.sub(r">\s+<", "><", s)
    s = re.sub(r"\s+", " ", s)
    return s.strip()


def check():
    """Verify the markup in index.html is still exactly what the browser
    builds from script.js (guideline rule 7). Does not write anything."""
    built = render()
    page = io.open(TARGET, encoding="utf-8").read()
    m = re.search(re.escape(BEGIN) + r"(.*?)" + re.escape(END), page, re.S)
    if not m:
        print("FAIL: index.html has no BUILD:packages block")
        return 1
    inner = re.search(r'<div class="package-grid".*?>(.*)</div>', m.group(1), re.S)
    if not inner:
        print("FAIL: could not read the package grid out of index.html")
        return 1
    a, b = normalise(inner.group(1)), normalise(built)
    if a == b:
        print("CHECK ok: the static package markup in index.html is identical to "
              "buildPackagesHtml() in the browser (%d elements compared)"
              % built.count("<"))
        return 0
    print("FAIL: index.html has drifted from script.js. Re-run without --check.")
    for i in range(min(len(a), len(b))):
        if a[i] != b[i]:
            print("  first difference at character %d" % i)
            print("  html : ..." + a[max(0, i - 60):i + 60])
            print("  built: ..." + b[max(0, i - 60):i + 60])
            break
    else:
        print("  lengths differ: html %d, built %d" % (len(a), len(b)))
    return 1


def main():
    if "--check" in sys.argv:
        return check()
    markup = indent(render())
    page = io.open(TARGET, encoding="utf-8").read()

    block = (
        '%s\n'
        '          <!-- Generated by build/prerender_packages.py from the `packages`\n'
        '               array in script.js. Do not edit by hand: re-run the script. -->\n'
        '          <div class="package-grid" id="packagesGrid" aria-live="polite" data-prerendered="1">\n'
        '%s\n'
        '          </div>\n'
        '          %s' % (BEGIN, markup, END)
    )

    if BEGIN in page:
        page = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block, page, flags=re.S)
    else:
        empty = '<div class="package-grid" id="packagesGrid" aria-live="polite"></div>'
        if empty not in page:
            sys.exit("packagesGrid placeholder not found in index.html")
        page = page.replace(empty, block)

    io.open(TARGET, "w", encoding="utf-8", newline="").write(page)
    print("index.html: package markup written (%d characters, %d cards)"
          % (len(markup), len(__import__("re").findall(chr(60)+"article class=\"pkg-card", markup))))


if __name__ == "__main__":
    sys.exit(main())
