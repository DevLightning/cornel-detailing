# -*- coding: utf-8 -*-
"""Write the package price table into every page that has the BUILD markers.

Prices are read from the `packages` array in script.js, so a price is only ever
typed once in this project.

Usage:  python build/gen_price_table.py
"""
import io, os, re, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkgdata import ROOT, load_packages

RECOMMENDED = 9
BEGIN = "<!-- BUILD:pricetable -->"
END = "<!-- /BUILD:pricetable -->"
PAD = "          "


def esc(s):
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def build_table(pkgs):
    rows = []
    for p in pkgs:
        cls = ' class="is-recommended"' if p["number"] == RECOMMENDED else ""
        rows.append(
            '%s    <tr%s>\n'
            '%s      <td class="pt-pkg">\n'
            '%s        <span class="pt-name">%s</span>\n'
            '%s        <span class="pt-cat">%s \u00b7 Paket %d</span>\n'
            '%s      </td>\n'
            '%s      <td class="pt-price" data-label="PKW">%s</td>\n'
            '%s      <td class="pt-price" data-label="SUV / Kombi">%s</td>\n'
            '%s      <td class="pt-price" data-label="Van">%s</td>\n'
            '%s    </tr>'
            % (PAD, cls, PAD, PAD, esc(p["title"]), PAD, esc(p["category"]), p["number"],
               PAD, PAD, esc(p["prices"]["pkw"]), PAD, esc(p["prices"]["suv"]),
               PAD, esc(p["prices"]["van"]), PAD)
        )
    return (
        '%s<!-- Generated by build/gen_price_table.py from the `packages` array in\n'
        '%s     script.js. Do not edit by hand: re-run the script. -->\n'
        '%s<table class="price-table">\n'
        '%s  <thead>\n'
        '%s    <tr><th scope="col">Paket</th><th scope="col">PKW</th>'
        '<th scope="col">SUV / Kombi</th><th scope="col">Van</th></tr>\n'
        '%s  </thead>\n'
        '%s  <tbody>\n%s\n%s  </tbody>\n'
        '%s</table>\n'
        '%s<p class="price-table-note">\n'
        '%s  Alle Preise in EUR. Aufgrund der Kleinunternehmerregelung gem\u00e4\u00df\n'
        '%s  \u00a7 6 Abs. 1 Z 27 UStG wird keine Umsatzsteuer berechnet. Bei extremer\n'
        '%s  Verschmutzung kann bei den Innen-Paketen ein Aufschlag von bis zu\n'
        '%s  \u20ac 50,- dazukommen.\n'
        '%s</p>\n'
        '%s' % (PAD, PAD, PAD, PAD, PAD, PAD, PAD, "\n".join(rows), PAD, PAD,
                PAD, PAD, PAD, PAD, PAD, PAD, PAD)
    )


def main():
    pkgs = load_packages()
    table = build_table(pkgs)
    pattern = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)
    touched = 0
    for name in sorted(os.listdir(ROOT)):
        if not name.endswith(".html"):
            continue
        path = os.path.join(ROOT, name)
        page = io.open(path, encoding="utf-8").read()
        if BEGIN not in page:
            continue
        page = pattern.sub(lambda m: BEGIN + "\n" + table + END, page)
        io.open(path, "w", encoding="utf-8", newline="").write(page)
        print("%s: price table written (%d rows)" % (name, len(pkgs)))
        touched += 1
    if not touched:
        print("no page contains the %s marker" % BEGIN)
    return 0


if __name__ == "__main__":
    sys.exit(main())
